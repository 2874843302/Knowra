"""Build on-demand WOFF2 subsets from the pinned official Xiaolai release.

Usage: .venv/Scripts/python scripts/subset-board-font.py path/to/Xiaolai-Regular.ttf
Build-only requirements: fonttools==4.67.0 brotli==1.2.1.
Download: https://github.com/lxgw/kose-font/releases/tag/v3.126
"""
import hashlib
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
digest = hashlib.sha256(source.read_bytes()).hexdigest()
assert digest == "e2f68daf0e72777a8cf58bc83de1b98634b251e537ddbfca24b0ae50d1802da2", "Unexpected upstream font"
out = ROOT / "public/fonts/board"
out.mkdir(parents=True, exist_ok=True)
font = TTFont(source)
supported = set(font.getBestCmap())
# Current course prose and punctuation load together; arbitrary imported lessons
# can request every other upstream glyph through disjoint unicode ranges.
common = set(range(0x20, 0x100)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040))
for file in sorted((ROOT / "src").rglob("*")):
    if file.suffix in {".js", ".jsx", ".json"}:
        common.update(map(ord, file.read_text(encoding="utf-8")))
common &= supported
# A single supplemental face covers common Chinese in newly authored lessons;
# don't force a short new lesson to request dozens of scattered Unicode shards.
gb_level_one = set()
for high in range(0xB0, 0xD8):
    for low in range(0xA1, 0xFF):
        try:
            gb_level_one.add(ord(bytes([high, low]).decode("gb2312")))
        except UnicodeDecodeError:
            pass
supplement = (gb_level_one & supported) - common
remaining = sorted(supported - common - supplement)
groups = [sorted(common), sorted(supplement)] + [remaining[i:i + 512] for i in range(0, len(remaining), 512)]
old_manifest = out / "manifest.json"
if old_manifest.exists():
    for entry in json.loads(old_manifest.read_text(encoding="utf-8"))["subsets"]:
        old_file = (out / entry["file"]).resolve()
        assert old_file.parent == out.resolve() and old_file.name.startswith("board-")
        old_file.unlink(missing_ok=True)

def unicode_ranges(points):
    runs = []
    start = previous = points[0]
    for point in points[1:]:
        if point != previous + 1:
            runs.append((start, previous))
            start = point
        previous = point
    runs.append((start, previous))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)

css = ["/* Xiaolai 3.126, OFL-1.1; generated by scripts/subset-board-font.py. */"]
manifest = {"upstream": "https://github.com/lxgw/kose-font/releases/tag/v3.126", "sha256": digest, "family": "Knowra Board Hand", "glyphs": len(supported), "subsets": []}
for i, points in enumerate(groups):
    face = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.flavor = "woff2"
    options.recalc_timestamp = False
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    options.name_legacy = True
    options.name_languages = ["*"]
    cutter = subset.Subsetter(options=options)
    cutter.populate(unicodes=points)
    cutter.subset(face)
    # Explicit derivative family; retain copyright and license metadata.
    names = {1: "Knowra Board Hand", 2: "Regular", 3: f"KnowraBoardHand-3.126-{i}", 4: "Knowra Board Hand", 6: "KnowraBoardHand-Regular"}
    for record in face["name"].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    face.flavor = "woff2"
    name = f"board-{i:03}.woff2"
    face.save(out / name)
    ranges = unicode_ranges(points)
    css.append(f'@font-face {{\n  font-family: "Knowra Board Hand";\n  src: url("/fonts/board/{name}") format("woff2");\n  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n  unicode-range: {ranges};\n}}')
    manifest["subsets"].append({"file": name, "bytes": (out / name).stat().st_size, "unicodeRange": ranges})
    print(f"{name}: {len(points)} codepoints, {(out / name).stat().st_size} bytes", flush=True)
(out / "board.css").write_text("\n".join(css) + "\n", encoding="utf-8")
(out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
assert sum(map(len, groups)) == len(supported)
print(f"Preserved all {len(supported)} upstream codepoints in {len(groups)} non-overlapping subsets.")
